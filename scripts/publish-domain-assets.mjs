/** Publish approved art/audio files and generated read-only runtime indices. No downloads. */
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {DOMAIN_GLYPHS,NUMBER_COLORS,NUMBER_STYLES} from '../assets/vfx/domain/domain-numbers.mjs';
const root=new URL('../',import.meta.url),audio=new URL('assets/audio/domain/',root);
const manifest=JSON.parse(readFileSync(new URL('audio-manifest.json',audio),'utf8'));
const audioOut=new URL('public/assets/audio/domain/',root),fxOut=new URL('public/assets/vfx/domain/',root);
mkdirSync(audioOut,{recursive:true});mkdirSync(fxOut,{recursive:true});
const audioIndex={};
for(const cue of manifest.clips){
  writeFileSync(new URL(cue.file,audioOut),readFileSync(new URL(cue.file,audio)));
  audioIndex[cue.id]={file:`assets/audio/domain/${cue.file}`,duration:cue.duration,loop:cue.loop};
}
for(const key of ['field','blackhole','impact'])
  writeFileSync(new URL(`${key}-128.png`,fxOut),readFileSync(new URL(`assets/vfx/domain/prototype/${key}-128.png`,root)));
writeFileSync(new URL('domain-glyph-mask.png',fxOut),readFileSync(new URL('assets/vfx/domain/numbers/domain-glyph-mask.png',root)));
const talentIndex=Object.fromEntries(Object.entries(manifest.talents).map(([name,value])=>[name,value.learn]));
const upgradeIndex=Object.fromEntries(Object.entries(manifest.weaponUpgrades).map(([name,value])=>[name,value.learn]));
const header='/** Generated by scripts/publish-domain-assets.mjs; edit the owning assets, not this file. */\n';
writeFileSync(new URL('src/game/data/domainAudio.ts',root),header+
  `export const DOMAIN_AUDIO = ${JSON.stringify(audioIndex,null,2)} as const;\n`+
  'export type DomainSoundId = keyof typeof DOMAIN_AUDIO;\n'+
  `export const DOMAIN_TALENT_AUDIO = ${JSON.stringify(talentIndex,null,2)} as const;\n`+
  `export const DOMAIN_UPGRADE_AUDIO = ${JSON.stringify(upgradeIndex,null,2)} as const;\n`);
writeFileSync(new URL('src/game/data/domainNumberArt.ts',root),header+
  `export const DOMAIN_GLYPHS = ${JSON.stringify(DOMAIN_GLYPHS,null,2)} as const;\n`+
  `export const DOMAIN_NUMBER_COLORS = ${JSON.stringify(NUMBER_COLORS,null,2)} as const;\n`+
  `export const DOMAIN_NUMBER_STYLES = ${JSON.stringify(NUMBER_STYLES,null,2)} as const;\n`);
console.log(JSON.stringify({audioFiles:manifest.clips.length,vfxTextures:3,numberGlyphs:Object.keys(DOMAIN_GLYPHS).length}));
