import { expect, test } from "@playwright/test";

import { dismissStartTalent } from "./e2e-helpers";
test("enemy attack snapshots through real browser simulation", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await page.locator("#btn-start").click();
  await dismissStartTalent(page);
  await page.waitForFunction(() => window.__PIXEL_ROGUE__?.core.enemies.length);
  await page.waitForTimeout(8000);
  await page.screenshot({ path: "output/playwright/d2b-battle-8s.png" });
  const result = await page.evaluate(() => {
    const g = window.__PIXEL_ROGUE__!.core;
    g.togglePause();
    g.state = "play";
    g.enemies = []; g.ebullets = []; g.bullets = [];
    g.spawnCd = 1e9; g.player.fireCd = 1e9;
    g.player.hp = g.player.maxhp = 1000;
    g.spawnEnemy("shooter");
    const shooter = g.enemies[0];
    shooter.x = g.player.x - 100; shooter.y = g.player.y;
    shooter.speed = 0; shooter.shootCd = 0; shooter.globalDamageBonus = 0.2;
    g.update(1 / 60);
    const bullet = g.ebullets[0];
    const launch = { damage: bullet.dmg, bonus: bullet.stats?.globalDamageBonus };
    shooter.globalDamageBonus = 0.9; shooter.dmg = 999; g.enemies = [];
    bullet.x = g.player.x; bullet.y = g.player.y; bullet.vx = bullet.vy = 0;
    g.player.hurtCd = 0; g.player.dashT = 0;
    const beforeShot = g.player.hp;
    g.update(1 / 60);
    const shotLoss = beforeShot - g.player.hp;
    g.spawnEnemy("bomber");
    const bomber = g.enemies[0];
    bomber.x = g.player.x; bomber.y = g.player.y; bomber.speed = 0;
    bomber.fuse = 0.01; bomber.globalDamageBonus = 0.5;
    g.player.hurtCd = 0; g.player.dashT = 0;
    const beforeBlast = g.player.hp;
    g.update(1 / 60);
    const blast = { loss: beforeBlast - g.player.hp, damage: bomber.dmg, noDrop: bomber.noDrop, hp: bomber.hp, dead: bomber.dead };
    g.enemies = []; g.ebullets = [];
    g.spawnEnemy("slime");
    const enemy = g.enemies[0];
    enemy.x = g.player.x; enemy.y = g.player.y; enemy.speed = 0; enemy.globalDamageBonus = 0.25;
    g.player.hurtCd = 0; g.player.dashT = 0;
    const beforeContact = g.player.hp;
    g.update(1 / 60);
    const first = beforeContact - g.player.hp;
    enemy.globalDamageBonus = 0.5; enemy.x = g.player.x; enemy.y = g.player.y;
    g.player.hurtCd = 0; g.player.dashT = 0;
    const beforeSecond = g.player.hp;
    g.update(1 / 60);
    return { launch, shotLoss, blast, contact: { damage: enemy.dmg, first, second: beforeSecond - g.player.hp } };
  });
  expect(result.launch.bonus).toBe(0.2);
  expect(result.shotLoss).toBeCloseTo(result.launch.damage * 1.2, 10);
  expect(result.blast.loss).toBeCloseTo(result.blast.damage * 1.5, 10);
  expect(result.blast).toMatchObject({ noDrop: true, hp: 0, dead: true });
  expect(result.contact.first).toBeCloseTo(result.contact.damage * 1.25, 10);
  expect(result.contact.second).toBeCloseTo(result.contact.damage * 1.5, 10);
  expect(errors).toEqual([]);
});
